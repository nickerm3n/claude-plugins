"""DDD review policy: .sdlc/domain-map.yml maps paths to core | supporting | generic.

  domain.py classify [--base main]     class of every changed file and the strictest class of the diff (for the PR body)
  domain.py codeowners                 print a CODEOWNERS file from domain-map owners (a human installs it)
  domain.py checklist                  branch protection checklist for the configured policy
Globs: `*` stays within one path segment, `**` crosses segments.
"""

import argparse
import os
import re
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))

import config  # noqa: E402
import yamlish  # noqa: E402
from checks import repo  # noqa: E402

ORDER = {"generic": 0, "supporting": 1, "core": 2}


def glob_rx(glob):
    out, i = [], 0
    while i < len(glob):
        if glob[i : i + 3] == "**/":
            out.append("(?:.*/)?")
            i += 3
        elif glob[i : i + 2] == "**":
            out.append(".*")
            i += 2
        elif glob[i] == "*":
            out.append("[^/]*")
            i += 1
        elif glob[i] == "?":
            out.append("[^/]")
            i += 1
        else:
            out.append(re.escape(glob[i]))
            i += 1
    return re.compile("^" + "".join(out) + "$")


def load_map(cfg):
    path = os.path.join(cfg["_root"], cfg["paths"]["domain_map"])
    if not os.path.exists(path):
        raise SystemExit("%s not found: run /sdlc:init" % path)
    data = yamlish.load_file(path) or {}
    domains = data.get("domains") or []
    for d in domains:
        if d.get("type") not in ORDER:
            raise SystemExit("domain %s: type must be core, supporting or generic" % (d.get("name") or d.get("path")))
    return data.get("default", "supporting"), domains


def classify(path, default, domains):
    """The last matching entry wins, like CODEOWNERS."""
    hit = None
    for d in domains:
        paths = d["path"] if isinstance(d["path"], list) else [d["path"]]
        if any(glob_rx(p).match(path) for p in paths):
            hit = d
    return (hit or {}).get("type", default), (hit or {}).get("name")


def codeowners(domains):
    lines = ["# Generated by sdlc domain.py from .sdlc/domain-map.yml. Core paths need an owner review."]
    for d in domains:
        owners = d.get("owners") or []
        if not owners:
            continue
        for p in d["path"] if isinstance(d["path"], list) else [d["path"]]:
            pattern = "/" + p.lstrip("/")
            lines.append("%s %s  # %s%s" % (pattern, " ".join(owners), d["type"], (" · " + d["name"]) if d.get("name") else ""))
    return "\n".join(lines) + "\n"


def main(argv=None):
    ap = argparse.ArgumentParser(prog="domain.py")
    ap.add_argument("--config", default=".sdlc/config.yml")
    sub = ap.add_subparsers(dest="cmd", required=True)
    p = sub.add_parser("classify")
    p.add_argument("--base")
    sub.add_parser("codeowners")
    sub.add_parser("checklist")
    a = ap.parse_args(argv)
    cfg = config.load(a.config)
    default, domains = load_map(cfg)
    if a.cmd == "classify":
        files = repo.changed_files(cfg["_root"], a.base or cfg["project"]["base_branch"], cfg["paths"]["runs"]) or []
        worst = "generic"
        for f in files:
            kind, name = classify(f, default, domains)
            if ORDER[kind] > ORDER[worst]:
                worst = kind
            print("%-10s %s%s" % (kind, f, ("  (" + name + ")") if name else ""))
        pol = cfg["review_policy"].get(worst, {})
        print("Domain class of this change: %s · review: human %s, depth %s" % (worst, pol.get("human"), pol.get("depth")))
    elif a.cmd == "codeowners":
        sys.stdout.write(codeowners(domains))
    elif a.cmd == "checklist":
        print("Branch protection for %s (set by a human in GitHub settings):" % cfg["project"]["base_branch"])
        print("- [ ] Require a pull request before merging")
        print("- [ ] Require review from Code Owners (CODEOWNERS from `domain.py codeowners`)")
        print("- [ ] Required approvals >= 1 (core policy: %s)" % cfg["review_policy"].get("core", {}).get("human"))
        print("- [ ] Require status checks: the sdlc ci-quality job")
        print("- [ ] Do not allow bypassing the above settings")
    return 0


if __name__ == "__main__":
    sys.exit(main())
